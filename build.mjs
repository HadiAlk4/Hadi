// Builds the blog from Markdown files in writing/.
//
// Each writing/<slug>.md becomes writing/<slug>/index.html, and the list of
// posts is written into index.html (between the posts:start/end markers) so
// the Writing panel can show it without fetching anything.
//
// Front matter: title, date (YYYY-MM-DD), optional summary, optional
// draft: true. Files starting with "_" are never published.

import { readFileSync, writeFileSync, readdirSync, mkdirSync, rmSync, existsSync } from "node:fs";
import { join } from "node:path";
import { marked } from "marked";

const ROOT = new URL(".", import.meta.url).pathname;
const SRC = join(ROOT, "writing");
const GENERATED = "<!-- generated by build.mjs -->";

function parse(file) {
  const raw = readFileSync(join(SRC, file), "utf8");
  const match = raw.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$/);
  if (!match) throw new Error(`${file}: missing front matter`);

  const meta = {};
  for (const line of match[1].split(/\r?\n/)) {
    const kv = line.match(/^(\w+):\s*(.*)$/);
    if (kv) meta[kv[1]] = kv[2].replace(/^(["'])(.*)\1$/, "$2");
  }
  if (!meta.title) throw new Error(`${file}: missing title`);
  const date = meta.date || meta.pubDate;
  if (!/^\d{4}-\d{2}-\d{2}$/.test(date || "")) throw new Error(`${file}: date must be YYYY-MM-DD`);

  const body = match[2].trim();
  const html = marked.parse(body);
  const text = html
    .replace(/<[^>]+>/g, " ")
    .replace(/&(amp|lt|gt|quot|#39);/g, (_, e) => ({ amp: "&", lt: "<", gt: ">", quot: '"', "#39": "'" })[e])
    .replace(/\s+/g, " ")
    .trim();
  const summary = meta.summary || (text.length > 160 ? text.slice(0, 157).replace(/\s+\S*$/, "") + "…" : text);

  return {
    slug: file.replace(/\.md$/, ""),
    title: meta.title,
    date,
    summary,
    draft: meta.draft === "true",
    html,
    minutes: Math.max(1, Math.round(text.split(" ").length / 220)),
  };
}

const escape = (s) =>
  s.replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c]);

const formatDate = (iso) =>
  new Date(`${iso}T00:00:00Z`).toLocaleDateString("en-AU", { day: "numeric", month: "long", year: "numeric", timeZone: "UTC" });

function page(post) {
  return `<!doctype html>
${GENERATED}
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>${escape(post.title)} · Hadi</title>
  <meta name="description" content="${escape(post.summary)}">
  <meta property="og:title" content="${escape(post.title)}">
  <meta property="og:description" content="${escape(post.summary)}">
  <meta property="og:type" content="article">
  <link rel="preconnect" href="https://fonts.googleapis.com">
  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
  <link href="https://fonts.googleapis.com/css2?family=Instrument+Serif&family=Inter:wght@400;500&display=swap" rel="stylesheet">
  <link rel="stylesheet" href="../post.css">
</head>
<body>
  <div class="scene" aria-hidden="true"><img src="../../scene.jpg" alt=""><div class="tint"></div></div>

  <main class="post">
    <a class="back" href="../../index.html#writing">← Writing</a>
    <header>
      <h1>${escape(post.title)}</h1>
      <p class="meta"><time datetime="${post.date}">${formatDate(post.date)}</time> · ${post.minutes} min read</p>
    </header>
    <article>
${post.html}
    </article>
  </main>

  <script src="../../time.js"></script>
  <script src="../../typewriter.js"></script>
  <script src="../post.js"></script>
</body>
</html>
`;
}

const posts = readdirSync(SRC)
  .filter((f) => f.endsWith(".md") && !f.startsWith("_"))
  .map(parse)
  .filter((p) => !p.draft)
  .sort((a, b) => b.date.localeCompare(a.date));

for (const post of posts) {
  mkdirSync(join(SRC, post.slug), { recursive: true });
  writeFileSync(join(SRC, post.slug, "index.html"), page(post));
}

// Remove pages for posts that were deleted, renamed or turned back into drafts.
const live = new Set(posts.map((p) => p.slug));
for (const entry of readdirSync(SRC, { withFileTypes: true })) {
  const index = join(SRC, entry.name, "index.html");
  if (entry.isDirectory() && !live.has(entry.name) && existsSync(index) && readFileSync(index, "utf8").includes(GENERATED)) {
    rmSync(join(SRC, entry.name), { recursive: true });
  }
}

const list = posts.map(({ slug, title, date, minutes }) => ({ slug, title, date: formatDate(date), iso: date, minutes }));
const indexPath = join(ROOT, "index.html");
const indexHtml = readFileSync(indexPath, "utf8");
const marker = /(\/\* posts:start \*\/)[\s\S]*?(\/\* posts:end \*\/)/;
if (!marker.test(indexHtml)) throw new Error("index.html: posts markers not found");
const json = JSON.stringify(list, null, 2).replace(/\n/g, "\n    ");
writeFileSync(indexPath, indexHtml.replace(marker, (_, start, end) => `${start}\n    const POSTS = ${json};\n    ${end}`));

console.log(`Built ${posts.length} post${posts.length === 1 ? "" : "s"}: ${posts.map((p) => p.slug).join(", ") || "none"}`);
